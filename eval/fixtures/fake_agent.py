#!/usr/bin/env python3
"""Deterministic fake SWE-bench agent used by smoke tests and CI fixtures.

It only reacts to information the runner exposes through environment variables
and CLI arguments; it never reads the pinned dataset (so a leak of gold data
would be visible in the captured inputs).
"""

from __future__ import annotations

import argparse
import json
import os
import sys
import time
from pathlib import Path

MARKER = "FAKE_HARNESS_GOOD"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--workspace", required=True, type=Path)
    parser.add_argument("--case-dir", required=True, type=Path)
    parser.add_argument("--instruction", required=True, type=Path)
    args = parser.parse_args(argv)

    behavior = os.environ.get("SELF_HARNESS_FAKE_AGENT_BEHAVIOR", "complete").strip().lower()
    worker_sleep = float(os.environ.get("SELF_HARNESS_FAKE_AGENT_SLEEP", "0") or 0)
    trace_path = Path(
        os.environ.get("SELF_HARNESS_AGENT_TRACE", str(args.case_dir / "agent_trace.jsonl"))
    )
    trace_path.parent.mkdir(parents=True, exist_ok=True)
    (args.case_dir / "agent_cwd.txt").write_text(str(args.workspace) + "\n", encoding="utf-8")
    (args.case_dir / "agent_env.json").write_text(
        json.dumps(
            {
                "candidate_workspace": os.environ.get("SELF_HARNESS_CANDIDATE_WORKSPACE"),
                "model": os.environ.get("SELF_HARNESS_MODEL"),
                "task_id": os.environ.get("SELF_HARNESS_TASK_ID"),
                "tool_timeout_s": os.environ.get("SELF_HARNESS_TOOL_TIMEOUT_S"),
                "task_timeout_s": os.environ.get("SELF_HARNESS_TASK_TIMEOUT_S"),
            },
            indent=2,
            sort_keys=True,
        )
        + "\n",
        encoding="utf-8",
    )

    if worker_sleep:
        time.sleep(worker_sleep)
    if behavior == "timeout":
        time.sleep(float(os.environ.get("SELF_HARNESS_FAKE_AGENT_TIMEOUT_SLEEP", "3600")))
        return 0
    if behavior == "error":
        print("fake agent deliberate failure", file=sys.stderr)
        return 7

    harness_marker = _harness_contains_marker()
    always_resolve = os.environ.get("SELF_HARNESS_FAKE_AGENT_ALWAYS_RESOLVE", "").lower() in {
        "1",
        "true",
        "yes",
    }
    solved = always_resolve or harness_marker
    solution = args.workspace / "solution.py"
    solution.write_text(
        "# Generated by the fixture agent for the SWE-bench smoke test.\n"
        "def solved():\n"
        f"    return {solved!r}\n"
        + ("# SOLVED\n" if solved else "# NOT_RESOLVED\n"),
        encoding="utf-8",
    )
    trace_path.write_text(
        json.dumps(
            {
                "type": "tool_call",
                "tool": "write_file",
                "path": "solution.py",
                "tool_calls": [{"name": "write_file", "args": {"path": "solution.py"}}],
            }
        )
        + "\n",
        encoding="utf-8",
    )
    print(f"fake agent completed (harness_marker={harness_marker}, solved={solved})")
    return 0


def _harness_contains_marker() -> bool:
    raw = os.environ.get("SELF_HARNESS_CANDIDATE_WORKSPACE")
    if not raw:
        return False
    root = Path(raw)
    if not root.exists():
        return False
    for path in root.rglob("*.py"):
        try:
            if MARKER in path.read_text(encoding="utf-8", errors="replace"):
                return True
        except OSError:
            continue
    return False


if __name__ == "__main__":
    raise SystemExit(main())
